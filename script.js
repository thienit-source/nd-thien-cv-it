function applyLanguage(language) {
  const dictionary = translations[language];
  if (!dictionary) return;
  document.documentElement.lang = language;
  document.title = language === "vi"
    ? "Nguyễn Đức Thiện | CV Hỗ trợ CNTT & Vận hành Hệ thống"
    : "Nguyen Duc Thien | IT Support & Systems Operations CV";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (value !== undefined) element.textContent = value;
  });

  document.querySelectorAll("[data-language]").forEach((button) => {
    const active = button.dataset.language === language;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  try { localStorage.setItem("thien-cv-language", language); } catch {}
}

document.addEventListener("DOMContentLoaded", () => {
  let language = "vi";
  try { language = localStorage.getItem("thien-cv-language") || "vi"; } catch {}
  applyLanguage(language);

  document.querySelectorAll("[data-language]").forEach((button) => {
    button.addEventListener("click", () => applyLanguage(button.dataset.language));
  });

  document.getElementById("print-cv")?.addEventListener("click", () => window.print());
});
